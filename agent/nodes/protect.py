class TestProductsReport:
    def test_returns_200(self, server):
        status, _, _ = get(server, "/products/report")
        assert status == 200

    def test_returns_all_products(self, server):
        _, _, data = get(server, "/products/report")
        assert len(data["products"]) == NUM_PRODUCTS

    def test_each_product_has_required_fields(self, server):
        _, _, data = get(server, "/products/report")
        for p in data["products"]:
            assert "id" in p
            assert "name" in p
            assert "category" in p
            assert "price" in p
            assert "units_sold" in p
            assert "demand_index" in p
            assert "score" in p

    def test_demand_index_is_positive(self, server):
        _, _, data = get(server, "/products/report")
        for p in data["products"]:
            assert p["demand_index"] > 0

    def test_scores_are_consistent_across_calls(self, server):
        """Caching must not change scores — result must be deterministic."""
        _, _, first = get(server, "/products/report")
        _, _, second = get(server, "/products/report")
        first_scores = {p["id"]: p["score"] for p in first["products"]}
        second_scores = {p["id"]: p["score"] for p in second["products"]}
        assert first_scores == second_scores

    def test_demand_index_stable_for_same_category(self, server):
        """Products in the same category must get the same demand_index."""
        _, _, data = get(server, "/products/report")
        by_category: dict = {}
        for p in data["products"]:
            cat = p["category"]
            by_category.setdefault(cat, []).append(p["demand_index"])
        for cat, indices in by_category.items():
            assert len(set(round(i, 6) for i in indices)) == 1, (
                f"demand_index must be identical for all products in category '{cat}'"
            )


