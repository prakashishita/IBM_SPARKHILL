def protect(state: AgentState) -> AgentState:
    """Write the behavioural test file and run it against original ShopLite."""

    TESTS_DIR.mkdir(parents=True, exist_ok=True)

    # Make the tests directory a package so pytest finds it cleanly
    init = TESTS_DIR / "__init__.py"
    if not init.exists():
        init.write_text("", encoding="utf-8")

    test_file = TESTS_DIR / "test_shoplite_behaviour.py"
    test_file.write_text(TEST_SOURCE, encoding="utf-8")
    print(f"[protect] Wrote test file → {test_file}")

    result = _run_tests(state["target_dir"])
    print(
        f"[protect] Baseline tests: {result['passed']} passed, "
        f"{result['failed']} failed, {result['errors']} errors."
    )
    if result["failed"] > 0 or result["errors"] > 0:
        print("[protect] WARNING: baseline tests are not all green. "
              "Review output before proceeding.")

    return {
        **state,
        "tests_dir": str(TESTS_DIR),
        "baseline_tests": result,
    }


def _run_tests(shoplite_dir: str) -> TestResult:
    """Run pytest and parse the summary line."""
    cmd = [
        sys.executable, "-m", "pytest",
        str(TESTS_DIR / "test_shoplite_behaviour.py"),
        "-v", "--tb=short", "-q",
        f"--rootdir={TESTS_DIR}",
    ]
    env = {**os.environ, "SHOPLITE_DIR": shoplite_dir}
    proc = subprocess.run(cmd, capture_output=True, text=True, env=env)
    output = proc.stdout + proc.stderr
    return _parse_pytest_output(output)


def _parse_pytest_output(output: str) -> TestResult:
    """Extract passed/failed/error counts from pytest's summary line."""
    import re
    passed = failed = errors = 0
    # e.g. "17 passed, 2 failed, 1 error in 12.34s"
    m = re.search(
        r"(\d+) passed|(\d+) failed|(\d+) error",
        output,
    )
    for match in re.finditer(
        r"(\d+)\s+(passed|failed|error)", output
    ):
        n, kind = int(match.group(1)), match.group(2)
        if kind == "passed":
            passed = n
        elif kind == "failed":
            failed = n
        elif kind == "error":
            errors = n
    return TestResult(
        passed=passed,
        failed=failed,
        errors=errors,
        output=output[-8192:],  # keep last 8 KB
    )
