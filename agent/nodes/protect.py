def _python():
    venv = SHOPLITE_DIR / ".venv" / "bin" / "python"
    return str(venv) if venv.exists() else sys.executable


@pytest.fixture(scope="session")
def server():
    """Start ShopLite once for the whole test session; stop it afterwards."""
    db_file = Path(tempfile.mkdtemp(prefix="shoplite-test-")) / "app.db"
    env = {
        **os.environ,
        "SHOPLITE_DB": str(db_file),
        "PORT": str(PORT),
        "SHOPLITE_DISABLE_WATCHER": "0",
    }
    python = _python()
    subprocess.run(
        [python, "seed.py"], cwd=SHOPLITE_DIR, env=env,
        check=True, capture_output=True,
    )
    proc = subprocess.Popen(
        [python, "app.py"], cwd=SHOPLITE_DIR, env=env,
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    # Wait until it accepts connections (up to 15 s)
    deadline = time.time() + 15
    while time.time() < deadline:
        if proc.poll() is not None:
            pytest.fail("ShopLite exited during startup")
        try:
            urllib.request.urlopen(BASE + "/api", timeout=1)
            break
        except OSError:
            time.sleep(0.2)
    else:
        proc.terminate()
        pytest.fail(f"ShopLite did not start within 15 s on port {PORT}")

    yield BASE

    proc.terminate()
    proc.wait(timeout=10)
    db_file.unlink(missing_ok=True)
    db_file.parent.rmdir()


def get(base, path):
    with urllib.request.urlopen(base + path) as r:
        return r.status, dict(r.headers), json.load(r)


def post(base, path, body):
    data = json.dumps(body).encode()
    req = urllib.request.Request(
        base + path, data=data, method="POST",
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req) as r:
        return r.status, dict(r.headers), json.load(r)


