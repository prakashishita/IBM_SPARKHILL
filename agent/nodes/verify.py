"""Verify node — runs the behavioural test suite against the patched worktree.

The tests generated by the Protect node are re-run with SHOPLITE_DIR
pointing at the worktree copy of shoplite so we exercise the refactored
code.  Any regression (failure or new error) is surfaced clearly so the
human can decide whether to proceed to measurement.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

from agent.state import AgentState, TestResult
from agent.nodes.protect import TESTS_DIR, _parse_pytest_output


def verify(state: AgentState) -> AgentState:
    """Run behavioural tests against the worktree shoplite copy."""
    worktree_dir = state.get("worktree_dir", "")
    if not worktree_dir:
        print("[verify] No worktree found — skipping verification.")
        return {**state, "post_apply_tests": TestResult(
            passed=0, failed=0, errors=1,
            output="No worktree available.",
        )}

    # Derive the shoplite path inside the worktree from the original target_dir
    target = Path(state["target_dir"])
    repo_root_result = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        cwd=str(target), capture_output=True, text=True,
    )
    repo_root = repo_root_result.stdout.strip()
    rel = str(target.relative_to(repo_root))
    wt_shoplite = str(Path(worktree_dir) / rel)

    print(f"[verify] Running tests against worktree shoplite at {wt_shoplite}")

    cmd = [
        sys.executable, "-m", "pytest",
        str(TESTS_DIR / "test_shoplite_behaviour.py"),
        "-v", "--tb=short", "-q",
        f"--rootdir={TESTS_DIR}",
    ]
    env = {**os.environ, "SHOPLITE_DIR": wt_shoplite}
    proc = subprocess.run(cmd, capture_output=True, text=True, env=env)
    result = _parse_pytest_output(proc.stdout + proc.stderr)

    baseline = state.get("baseline_tests", {})
    print(
        f"[verify] Post-patch tests: {result['passed']} passed, "
        f"{result['failed']} failed, {result['errors']} errors.  "
        f"(Baseline was: {baseline.get('passed', '?')} / "
        f"{baseline.get('failed', '?')} / {baseline.get('errors', '?')})"
    )

    if result["failed"] > 0 or result["errors"] > 0:
        print("[verify] ⚠️  Regressions detected — review before measuring.")
    else:
        print("[verify] ✓  All tests green after patching.")

    return {**state, "post_apply_tests": result}
